# analysis/web_browser.R -- the interactive web browser step.
# It writes (1) strym_browser.html: ONE self-contained file (plots, tables and an overview are embedded; no internet or
# R needed) that the researcher can open by double-clicking, e-mail or share; and (2) a small Shiny app (app.R, a
# template) that lets you page through the project's plots and tables live. Replace strym_step_web_browser() (or just
# the app / page text below) with the team's template when it is ready (see analysis/README.md).
#
# ctx$project_dir is the project folder (the browser lives in  <project>/07_interactive_browser/ ).
# Run the live app from the Interactive browser card in StRym, or:  Rscript -e 'shiny::runApp("<folder>", port = 3939)'

.BROWSER_APP <- r"---(
# StRym results browser (template, generated by StRym). It shows what the other analysis steps produced.
library(shiny); library(DT)
root <- normalizePath("..")                                    # the project folder
addResourcePath("proj", root)
files <- function(pattern) {                                   # only what the analysis steps wrote (the numbered folders), not the other files of the folder
  tops <- list.dirs(root, recursive = FALSE, full.names = FALSE)
  tops <- tops[grepl("^[0-9]{2}_", tops) & !tops %in% c("00_design", "07_interactive_browser")]
  f <- unlist(lapply(tops, function(d) file.path(d, list.files(file.path(root, d), pattern = pattern, recursive = TRUE, ignore.case = TRUE))))
  if (is.null(f)) character() else sort(f)
}
read_tab <- function(f) {                                      # csv / tsv, or a network .txt (GENIST: tab-separated; RTP-STAR: "A activates B" lines)
  if (grepl("\\.txt$", f, ignore.case = TRUE)) {
    if (!grepl("\t", readLines(f, n = 1, warn = FALSE), fixed = TRUE)) return(read.table(f, sep = " ", header = FALSE, fill = TRUE, stringsAsFactors = FALSE, quote = ""))
    return(read.delim(f, sep = "\t"))
  }
  read.delim(f, sep = if (grepl("\\.tsv$", f, ignore.case = TRUE)) "\t" else ",")
}
summary_file <- file.path(root, "run_summary.csv")

ui <- fluidPage(
  tags$head(tags$style(HTML("body{background:#F4F6FC} h2{color:#24347B} .nav-tabs>li.active>a{color:#24347B!important;border-bottom:3px solid #6F7D1C}"))),
  titlePanel("StRym results browser"),
  tabsetPanel(
    tabPanel("Summary", br(), DTOutput("summary")),
    tabPanel("Plots", br(), selectInput("plot", "Plot", choices = files("\\.(png|svg|jpg|jpeg)$"), width = "100%"),
             uiOutput("img")),
    tabPanel("Tables", br(), selectInput("tab", "Table", choices = files("(\\.(csv|tsv)$)|((network|cytoscape|biograph).*\\.txt$)"), width = "100%"),
             DTOutput("table"))
  )
)

server <- function(input, output, session) {
  output$summary <- renderDT({
    validate(need(file.exists(summary_file), "No run_summary.csv yet."))
    datatable(read.csv(summary_file), rownames = FALSE, options = list(pageLength = 15))
  })
  output$img <- renderUI({ req(input$plot); tags$img(src = paste0("proj/", input$plot), style = "max-width:100%;border:1px solid #E4EAF7;border-radius:6px") })
  output$table <- renderDT({
    req(input$tab)
    f <- file.path(root, input$tab)
    datatable(read_tab(f), rownames = FALSE, options = list(pageLength = 15, scrollX = TRUE))
  })
}
shinyApp(ui, server)
)---"

